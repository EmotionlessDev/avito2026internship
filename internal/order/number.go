package order

import (
	"fmt"
	"time"
)

// numberPrefix — «К» как «кухня»: номер произносят вслух в поддержке
// и на кухне, поэтому он начинается с буквы, а не с цифры.
const numberPrefix = "К"

// FormatNumber собирает человекочитаемый номер заказа: К-260907-0042.
//
// Дата берётся в часовом поясе заведения: повару и оператору поддержки
// важно, какой это был рабочий день у них, а не в UTC. Порядковый номер
// приходит из последовательности Postgres, поэтому уникален без блокировок;
// после 9999 заказов за день номер просто становится длиннее — это лучше,
// чем повтор.
func FormatNumber(at time.Time, sequence int64) string {
	return fmt.Sprintf("%s-%s-%04d", numberPrefix, at.Format("060102"), sequence)
}
