// Package kafkax — тонкая обвязка над Kafka: топики, продюсер, консьюмер.
//
// Kafka здесь не для доставки заказа в заведение — это делает Temporal,
// потому что ему нужен результат вызова. Kafka нужна наблюдателям, которым
// результат не важен и которых со временем больше: индексатор поиска,
// уведомления, витрина статистики (docs/DESIGN.md §5).
package kafkax

// Топики платформы. Имя — часть контракта: смена схемы события означает
// новый топик с суффиксом версии, а не тихое изменение старого.
const (
	// TopicCatalogEvents — изменения каталога. Компактируемый: по ключу
	// (item_id) остаётся последний снимок позиции, поэтому витрину поиска
	// можно пересобрать проигрыванием топика.
	TopicCatalogEvents = "catalog-events"
	// TopicOrderEvents — факты о заказах для наблюдателей.
	TopicOrderEvents = "order-events"
	// TopicDeadLetter — сообщения, которые консьюмер не смог обработать
	// после всех попыток. Лучше отложить одно сообщение, чем остановить
	// поток целиком.
	TopicDeadLetter = "dead-letter"
)

// Группы консьюмеров. Имя группы совпадает с именем в processed_events:
// по нему видно, кто и что уже применил.
const (
	GroupSearchIndexer = "search-indexer"
	GroupNotifier      = "notifier"
	// GroupWorkflowStarter — страховка на запуск процесса заказа: быстрый
	// путь идёт синхронно из HTTP-хендлера, а этот потребитель поднимает
	// процесс, если тот вызов не удался.
	GroupWorkflowStarter = "workflow-starter"
	// GroupMerchantStats — витрина показателей заведения за день (M8).
	GroupMerchantStats = "merchant-stats"
)
